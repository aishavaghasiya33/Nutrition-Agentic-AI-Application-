def check_input_safety(text: str) -> dict:
    """
    Validates user input for harmful intent or prompt injection attempts.
    Returns {"safe": bool, "reason": str}
    """
    if not text:
        return {"safe": True, "reason": ""}

    if len(text) > 2000:
        return {"safe": False, "reason": "Input too long. Please keep your message under 2,000 characters."}

    # Prompt injection guard
    injection_patterns = [
        r"ignore (previous|all|above) instructions",
        r"you are now",
        r"act as (a )?(?!nutrition|health|diet|coach)",
        r"jailbreak",
        r"DAN mode",
        r"<\s*script",
        r"system:\s*you",
        r"forget all previous",
    ]
    for pat in injection_patterns:
        if re.search(pat, text, re.IGNORECASE):
            return {
                "safe": False,
                "reason": "I can only assist with nutrition and health topics. Please keep your question relevant to diet and wellness.",
            }

    return {"safe": True, "reason": ""}


def check_output_safety(text: str) -> dict:
    """
    Scans AI-generated output for forbidden medical advice patterns.
    Returns {"safe": bool, "flagged": str}
    """
    for pat in FORBIDDEN_PATTERNS:
        if re.search(pat, text, re.IGNORECASE):
            return {"safe": False, "flagged": pat}
    return {"safe": True, "flagged": ""}


def get_condition_warnings(medical_history: str) -> list:
    """
    Returns condition-specific caution messages for the user's health conditions.
    """
    if not medical_history or medical_history.strip().lower() in ("none", "n/a", ""):
        return []
    warnings = []
    lower = medical_history.lower()
    for condition, advice in SENSITIVE_CONDITIONS.items():
        if condition in lower:
            warnings.append(
                f"**{condition.title()} detected** — please {advice}."
            )
    return warnings


def sanitize_user_input(value: str, field: str) -> str:
    """
    Strips potentially dangerous characters from user-supplied strings.
    """
    if not isinstance(value, str):
        return ""
    # Remove HTML / script tags
    clean = re.sub(r"<[^>]+>", "", value)
    # Remove SQL injection characters (for logging safety)
    clean = re.sub(r"[;'\"]", "", clean)
    # Limit individual field lengths
    limits = {"name": 80, "city": 80, "country": 80, "medical_history": 500, "question": 1000}
    limit = limits.get(field, 500)
    return clean.strip()[:limit]


def validate_user_profile(profile: dict) -> dict:
    """
    Validates all required fields of the user profile.
    Returns {"valid": bool, "errors": list}
    """
    errors = []

    name = str(profile.get("name", "")).strip()
    if not name or len(name) < 2:
        errors.append("Please provide a valid name (at least 2 characters).")

    try:
        age = int(profile.get("age", 0))
        if age < 5 or age > 110:
            errors.append("Age must be between 5 and 110.")
    except (ValueError, TypeError):
        errors.append("Age must be a valid number.")

    diet = str(profile.get("diet_preference", "")).lower().strip()
    valid_diets = ["vegetarian", "non-vegetarian", "vegan", "pescatarian"]
    if diet not in valid_diets:
        errors.append("Diet preference must be one of: Vegetarian, Non-Vegetarian, Vegan, Pescatarian.")

    city = str(profile.get("city", "")).strip()
    if not city:
        errors.append("City is required.")

    country = str(profile.get("country", "")).strip()
    if not country:
        errors.append("Country is required.")

    return {"valid": len(errors) == 0, "errors": errors}
